#!/usr/bin/env node
/* Builds the Chrome version into dist/chrome (or the directory given as the first argument).
 *
 * manifest.json is the Firefox manifest and the source of truth. The Chrome manifest is
 * that manifest with chrome/manifest.json merged over it (objects merge, other values
 * replace, null removes a key), plus the permission names Chrome spells differently.
 * The code in src/ is shared as is. Chrome runs the background as a service worker, so
 * the build writes one that loads the same scripts Firefox lists in background.scripts. */
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const SERVICE_WORKER = "service-worker.js";
const MAX_DESCRIPTION = 132; // Chrome's limit for the manifest description.
const PERMISSION_NAMES = { menus: "contextMenus" };
const COPY = ["src", "icons", "LICENSE"];

function readJson(file) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, file), "utf8"));
}

function isObject(v) {
  return v !== null && typeof v === "object" && !Array.isArray(v);
}

function merge(base, overrides) {
  const out = { ...base };
  for (const [key, value] of Object.entries(overrides)) {
    if (value === null) delete out[key];
    else if (isObject(value) && isObject(out[key])) out[key] = merge(out[key], value);
    else out[key] = value;
  }
  return out;
}

function chromeManifest(firefox = readJson("manifest.json"), overrides = readJson("chrome/manifest.json")) {
  const manifest = merge(firefox, overrides);
  manifest.permissions = (manifest.permissions || []).map((p) => PERMISSION_NAMES[p] || p);
  return manifest;
}

function serviceWorkerSource(scripts) {
  return (
    "\"use strict\";\n\n" +
    "// Generated by scripts/build-chrome.js: loads the scripts manifest.json lists in background.scripts.\n" +
    `importScripts(${scripts.map((s) => JSON.stringify(s)).join(", ")});\n`
  );
}

// Every file the manifest points at, relative to the package root.
function referencedFiles(manifest) {
  const files = new Set();
  const icons = (v) => (typeof v === "string" ? [v] : Object.values(v || {}));
  icons(manifest.icons).forEach((f) => files.add(f));
  icons(manifest.action && manifest.action.default_icon).forEach((f) => files.add(f));
  if (manifest.action && manifest.action.default_popup) files.add(manifest.action.default_popup);
  if (manifest.background && manifest.background.service_worker) files.add(manifest.background.service_worker);
  for (const cs of manifest.content_scripts || []) {
    [...(cs.js || []), ...(cs.css || [])].forEach((f) => files.add(f));
  }
  return [...files];
}

function check(manifest, outDir) {
  const problems = [];
  if ((manifest.description || "").length > MAX_DESCRIPTION) {
    problems.push(`description is ${manifest.description.length} characters; Chrome allows ${MAX_DESCRIPTION}`);
  }
  for (const f of referencedFiles(manifest)) {
    if (!fs.existsSync(path.join(outDir, f))) problems.push(`missing file: ${f}`);
  }
  if (problems.length) throw new Error("Chrome build is invalid:\n  " + problems.join("\n  "));
}

function build(outDir = path.join(ROOT, "dist", "chrome")) {
  const firefox = readJson("manifest.json");
  const manifest = chromeManifest(firefox);

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  for (const entry of COPY) {
    fs.cpSync(path.join(ROOT, entry), path.join(outDir, entry), { recursive: true });
  }
  fs.cpSync(path.join(ROOT, "chrome", "icons"), path.join(outDir, "icons"), { recursive: true });
  fs.writeFileSync(path.join(outDir, SERVICE_WORKER), serviceWorkerSource(firefox.background.scripts));
  fs.writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  check(manifest, outDir);
  return { outDir, manifest };
}

module.exports = { build, chromeManifest, merge, referencedFiles };

if (require.main === module) {
  const out = process.argv[2] ? path.resolve(process.argv[2]) : undefined;
  try {
    const { outDir } = build(out);
    console.log(`Built the Chrome version in ${path.relative(process.cwd(), outDir) || "."}`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
